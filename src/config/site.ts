export const primaryPhone = site.phones[0];

/** رابط واتساب مع ترميز صحيح للنص العربي */
export function whatsappLink(message: string = site.whatsappMessages.general, phone: Phone = primaryPhone) {
  return `https://wa.me/${phone.international}?text=${encodeURIComponent(message)}`;
}

export function serviceWhatsappLink(service: Pick<Service, "messageLabel">, phone: Phone = primaryPhone) {
  return whatsappLink(site.whatsappMessages.service(service.messageLabel), phone);
}

/** رابط اتصال بالصيغة الدولية لضمان العمل من أي شبكة */
export function telLink(phone: Phone = primaryPhone) {
  return `tel:+${phone.international}`;
}
